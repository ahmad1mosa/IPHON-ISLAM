class I18nManager {
  constructor() {
    this.currentLang = "ar";
    this.languages = APP_LANGUAGES;
    this.loadLanguage();
  }

  loadLanguage() {
    try {
      const saved = localStorage.getItem("gs_app_language");
      if (saved && TRANSLATIONS[saved]) {
        this.currentLang = saved;
      }
    } catch (e) {}
  }

  setLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) return;
    this.currentLang = langCode;
    try {
      localStorage.setItem("gs_app_language", langCode);
    } catch (e) {}

    this.applyLanguage();
  }

  getCurrentLanguage() {
    return this.currentLang;
  }

  t(key, replacements = {}) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ar;
    let text = dict[key] || (TRANSLATIONS.ar[key] || key);
    if (typeof text === "string" && replacements) {
      Object.keys(replacements).forEach(rKey => {
        text = text.replace(new RegExp(`\\{${rKey}\\}`, "g"), replacements[rKey]);
      });
    }
    return text;
  }

  applyLanguage() {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ar;
    document.documentElement.setAttribute("lang", this.currentLang);
    document.documentElement.setAttribute("dir", dict.dir);

    // تحديث كافة العناصر التي تحتوي على data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // تحديث كافة حقول الإدخال التي تحتوي على data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) {
        el.setAttribute("placeholder", dict[key]);
      }
    });

    // تحديث كافة العناوين التي تحتوي على data-i18n-title
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      if (dict[key]) {
        el.setAttribute("title", dict[key]);
      }
    });

    // إرسال حدث مخصص لتحديث القوائم الديناميكية
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: this.currentLang } }));
  }
}

window.I18nManager = new I18nManager();
window.TRANSLATIONS = TRANSLATIONS;
window.APP_LANGUAGES = APP_LANGUAGES;
