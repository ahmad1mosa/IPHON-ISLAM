class I18nManager {
  constructor() {
    this.currentLang = "ar";
    this.languages = APP_LANGUAGES;
    this.loadLanguage();
  }

  loadLanguage() {
    try {
      const saved = localStorage.getItem("gs_app_language");
      if (saved && TRANSLATIONS[saved]) {
        this.currentLang = saved;
      }
    } catch (e) {}
  }

  setLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) return;
    this.currentLang = langCode;
    try {
      localStorage.setItem("gs_app_language", langCode);
    } catch (e) {}

    this.applyLanguage();
  }

  t(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ar;
    return dict[key] || (TRANSLATIONS.ar[key] || key);
  }

  applyLanguage() {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ar;
    document.documentElement.setAttribute("lang", this.currentLang);
    document.documentElement.setAttribute("dir", dict.dir);

    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) {
        el.setAttribute("placeholder", dict[key]);
      }
    });

    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: this.currentLang } }));
  }
}

window.I18nManager = new I18nManager();
window.TRANSLATIONS = TRANSLATIONS;
window.APP_LANGUAGES = APP_LANGUAGES;
